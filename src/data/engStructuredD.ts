export function buildEngStructuredD(): McqQuestion[] {
  const list: McqQuestion[] = [];
  let seq = 1;
  const nextId = () => `esd_${String(seq++).padStart(4, '0')}`;

  // 1. Direct Grammar Drills (100+ MCQs)
  GRAMMAR_DRILLS.forEach((gd, i) => {
    list.push(
      buildMcq({
        id: nextId(),
        subjectId: 'eng',
        medicalGroup: 'eng',
        chapterId: 'eng_medical',
        visualLessonId: 'english_grammar',
        hscLevel: 'admission',
        difficulty: i % 3 === 0 ? 'medical' : i % 3 === 1 ? 'dental' : 'board',
        question: gd.q,
        correct: gd.a,
        distractors: [...gd.wrongs],
        explanation: gd.exp,
        reference: `Medical Admission English · ${gd.topic}`,
      })
    );
  });

  // 2. Grammar Rule Two-Way Matrix (50 × 2 = 100 MCQs)
  GRAMMAR_RULE_MATRIX.forEach((gm, i) => {
    const others = GRAMMAR_RULE_MATRIX.filter((x) => x.rule !== gm.rule);
    list.push(
      buildMcq({
        id: nextId(),
        subjectId: 'eng',
        medicalGroup: 'eng',
        chapterId: 'eng_medical',
        visualLessonId: 'english_grammar',
        hscLevel: 'admission',
        difficulty: i % 2 === 0 ? 'medical' : 'dental',
        question: `Which English grammar rule matches "${gm.application}"?`,
        correct: gm.rule,
        distractors: others.slice(i % 25, (i % 25) + 8).map((x) => x.rule),
        explanation: `${gm.rule}: ${gm.application}। উদাহরণ: ${gm.example}`,
        reference: 'Medical Admission English · Core Grammar Rules',
      })
    );
    list.push(
      buildMcq({
        id: nextId(),
        subjectId: 'eng',
        medicalGroup: 'eng',
        chapterId: 'eng_medical',
        visualLessonId: 'english_grammar',
        hscLevel: 'admission',
        difficulty: 'board',
        question: `Identify the valid example sentence demonstrating the rule "${gm.rule}":`,
        correct: gm.example,
        distractors: others.slice((i + 12) % 25, ((i + 12) % 25) + 8).map((x) => x.example),
        explanation: `"${gm.example}" বাক্যটি "${gm.rule}" নিয়মের সঠিক প্রয়োগ।`,
        reference: 'Medical Admission English · Grammar Examples',
      })
    );
  });

  // 3. Sentence Corrections (20 MCQs)
  SENTENCE_CORRECTION.forEach((sc, i) => {
    list.push(
      buildMcq({
        id: nextId(),
        subjectId: 'eng',
        medicalGroup: 'eng',
        chapterId: 'eng_medical',
        visualLessonId: 'english_grammar',
        hscLevel: 'admission',
        difficulty: i % 2 === 0 ? 'medical' : 'dental',
        question: `${sc.prompt} (Set #${i + 1})`,
        correct: sc.correct,
        distractors: [...sc.wrongs],
        explanation: sc.exp,
        reference: 'Medical Admission English · Sentence Correction',
      })
    );
  });

  return list;
}
